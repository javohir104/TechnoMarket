export function t(key, lang = "uz") {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.uz;
  return dict[key] ?? TRANSLATIONS.uz[key] ?? key;
}

export function formatPriceWithLang(n, lang = "uz") {
  const fmt = new Intl.NumberFormat(lang === "ru" ? "ru-RU" : lang === "en" ? "en-US" : "uz-UZ", {
    maximumFractionDigits: 0,
  });
  const currency = t("som", lang);
  return `${fmt.format(Number(n) || 0)} ${currency}`;
}
